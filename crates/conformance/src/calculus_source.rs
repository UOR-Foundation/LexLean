// --- references ------------------------------------------------------------

/// A type of `TargetSyntax`.
fn syntax_t(name: &str) -> Json {
    term::named(SYNTAX, name)
}

/// A call of a function of the module being generated.
fn call(function: &str, arguments: Vec<Json>) -> Json {
    lx::call(member(function), arguments)
}

/// A constructor of the module being generated, or a builtin such as
/// `Option.none`.
fn ctor(constructor: &str, arguments: Vec<Json>) -> Json {
    lx::construct(member(constructor), arguments)
}

fn syntax_ctor(constructor: &str, arguments: Vec<Json>) -> Json {
    lx::construct(term::member(SYNTAX, constructor), arguments)
}

fn owned(binders: &[&str]) -> Vec<String> {
    binders.iter().map(|binder| (*binder).to_owned()).collect()
}

/// A branch on a constructor of the module being generated, or a builtin.
fn branch(constructor: &str, binders: &[&str], body: Json) -> Json {
    lx::branch(member(constructor), owned(binders), body)
}

fn syntax_branch(constructor: &str, binders: &[&str], body: Json) -> Json {
    lx::branch(term::member(SYNTAX, constructor), owned(binders), body)
}

// --- TargetSyntax ----------------------------------------------------------
//
// The constructor tables are written once, in the syntax's own terms (a
// field of type `Ty` is the local `Ty`), and serve both the declarations and
// every match the semantics makes over them, so a match cannot fall out of
// step with the constructors it covers.

fn nullary(names: &[&'static str]) -> Constructors {
    names.iter().map(|name| (*name, Vec::new())).collect()
}

fn int_kind_constructors() -> Constructors {
    FIXED.iter().map(|(name, _)| (*name, Vec::new())).collect()
}

fn ty_constructors() -> Constructors {
    let ty = || local_t("Ty");
    vec![
        ("unit", vec![]),
        ("bool", vec![]),
        ("nat", vec![]),
        ("int", vec![]),
        ("fixed", vec![local_t("IntKind")]),
        ("string", vec![]),
        ("bytes", vec![]),
        ("ordering", vec![]),
        ("option", vec![ty()]),
        ("result", vec![ty(), ty()]),
        ("list", vec![ty()]),
        ("pair", vec![ty(), ty()]),
        ("adt", vec![nat_t()]),
        ("fn", vec![list_t(ty()), ty()]),
    ]
}

fn value_constructors() -> Constructors {
    let value = || local_t("Value");
    let mut out = vec![
        ("unit", vec![]),
        ("bool", vec![bool_t()]),
        ("nat", vec![nat_t()]),
        ("int", vec![int_t()]),
    ];
    out.extend(
        FIXED
            .iter()
            .map(|(name, kind)| (*name, vec![scalar_t(kind)])),
    );
    out.extend([
        ("string", vec![string_t()]),
        ("bytes", vec![scalar_t("bytes")]),
        ("ordering", vec![local_t("Order")]),
        ("none", vec![]),
        ("some", vec![value()]),
        ("ok", vec![value()]),
        ("error", vec![value()]),
        ("list", vec![list_t(value())]),
        ("pair", vec![value(), value()]),
        ("adt", vec![nat_t(), list_t(value())]),
        ("closure", vec![nat_t(), list_t(value())]),
    ]);
    out
}

fn shape_constructors() -> Constructors {
    let mut out = nullary(&SHAPES);
    out.push(("adt", vec![nat_t()]));
    out
}

fn prim_constructors() -> Constructors {
    let mut out = nullary(&PRIMITIVES);
    out.push(("convert", vec![local_t("IntKind")]));
    out.push(("parseDecimal", vec![local_t("Ty")]));
    out
}

fn expr_constructors() -> Constructors {
    let expr = || local_t("Expr");
    let exprs = || list_t(local_t("Expr"));
    vec![
        ("value", vec![local_t("Ty"), local_t("Value")]),
        ("var", vec![nat_t()]),
        ("let", vec![nat_t(), local_t("Ty"), expr(), expr()]),
        ("cond", vec![expr(), expr(), expr()]),
        ("match", vec![local_t("Ty"), expr(), list_t(local_t("Arm"))]),
        ("build", vec![local_t("Shape"), local_t("Ty"), exprs()]),
        ("call", vec![nat_t(), exprs()]),
        ("closure", vec![nat_t(), exprs()]),
        ("apply", vec![expr(), exprs()]),
        ("prim", vec![local_t("Prim"), exprs()]),
        ("first", vec![expr()]),
        ("second", vec![expr()]),
        ("field", vec![expr(), nat_t()]),
    ]
}

/// The `TargetSyntax` module: types, values, shapes, primitives,
/// expressions, and programs of the calculus.
#[must_use]
pub fn syntax_module() -> String {
    let declarations = vec![
        inductive("IntKind", int_kind_constructors()),
        inductive("Order", nullary(&["less", "same", "more"])),
        inductive("Ty", ty_constructors()),
        inductive("Value", value_constructors()),
        inductive("Shape", shape_constructors()),
        inductive("Prim", prim_constructors()),
        mutual("Code", inductive("Expr", expr_constructors())),
        mutual(
            "Code",
            inductive(
                "Arm",
                vec![(
                    "arm",
                    vec![local_t("Shape"), list_t(nat_t()), local_t("Expr")],
                )],
            ),
        ),
        structure("Adt", vec![("constructors", list_t(list_t(local_t("Ty"))))]),
        structure(
            "Function",
            vec![
                ("parameters", list_t(nat_t())),
                ("types", list_t(local_t("Ty"))),
                ("result", local_t("Ty")),
                ("body", local_t("Expr")),
            ],
        ),
        structure(
            "Program",
            vec![
                ("adts", list_t(local_t("Adt"))),
                ("functions", list_t(local_t("Function"))),
            ],
        ),
    ];
    module_tex(SYNTAX, &[], declarations)
}

