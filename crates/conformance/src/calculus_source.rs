fn add_steps() -> Json {
    definition(
        "addSteps",
        vec![
            parameter("result", outcome_t()),
            parameter("extra", nat_t()),
        ],
        outcome_t(),
        outcome_match(
            var("result"),
            Family::One,
            (
                &["computed", "steps"],
                produced(var("computed"), add(var("steps"), var("extra"))),
            ),
            (
                &["steps"],
                outcome("overflow", vec![add(var("steps"), var("extra"))]),
            ),
            stuck(),
            exhausted(),
        ),
    )
}

/// The innermost binding of a local wins: `let` and `bindAll` push to the
/// front.
fn lookup() -> Json {
    recursive(
        "environment",
        definition(
            "lookup",
            vec![
                parameter("environment", environment_t()),
                parameter("name", nat_t()),
            ],
            option_t(value_t()),
            list_match(
                var("environment"),
                none(value_t()),
                "entry",
                "rest",
                ite(
                    beq(first(var("entry")), var("name")),
                    some(value_t(), second(var("entry"))),
                    call("lookup", vec![var("rest"), var("name")]),
                ),
            ),
        ),
    )
}

/// The number of bindings a lookup of `name` examines before it finds
/// one: what reading a local costs beyond its own step.
fn depth() -> Json {
    recursive(
        "environment",
        definition(
            "depth",
            vec![
                parameter("environment", environment_t()),
                parameter("name", nat_t()),
            ],
            nat_t(),
            list_match(
                var("environment"),
                nat(0),
                "entry",
                "rest",
                ite(
                    beq(first(var("entry")), var("name")),
                    nat(0),
                    add(nat(1), call("depth", vec![var("rest"), var("name")])),
                ),
            ),
        ),
    )
}

/// A value's weight: one per node, and a string's characters or a byte
/// string's bytes. Every primitive is charged the weights of its operands
/// and of its result, so no primitive's work goes uncounted (§17.14).
fn weight(s: &Semantics) -> Json {
    let one_more_than = |term: Json| add(nat(1), term);
    let of = |binder: &str| call("weight", vec![var(binder)]);
    let of_all = |binder: &str| call("weights", vec![var(binder)]);
    let tag = s.ignored();
    let callee = s.ignored();
    let cases = vec![
        on(
            "string",
            &["text"],
            one_more_than(prim("length", vec![var("text")], nat_t())),
        ),
        on(
            "bytes",
            &["octets"],
            one_more_than(prim("length", vec![var("octets")], nat_t())),
        ),
        on("some", &["inner"], one_more_than(of("inner"))),
        on("ok", &["inner"], one_more_than(of("inner"))),
        on("error", &["inner"], one_more_than(of("inner"))),
        on("list", &["items"], one_more_than(of_all("items"))),
        on(
            "pair",
            &["left", "right"],
            one_more_than(add(of("left"), of("right"))),
        ),
        on("adt", &[&tag, "fields"], one_more_than(of_all("fields"))),
        on(
            "closure",
            &[&callee, "captured"],
            one_more_than(of_all("captured")),
        ),
    ];
    axioms(
        CLASSICAL,
        mutual(
            "Weight",
            recursive(
                "value",
                definition(
                    "weight",
                    vec![parameter("value", value_t())],
                    nat_t(),
                    s.value_match(var("value"), cases, nat(1)),
                ),
            ),
        ),
    )
}

/// The weights of a list of values.
fn weights() -> Json {
    axioms(
        CLASSICAL,
        mutual(
            "Weight",
            recursive(
                "values",
                definition(
                    "weights",
                    vec![parameter("values", values_t())],
                    nat_t(),
                    list_match(
                        var("values"),
                        nat(0),
                        "head",
                        "tail",
                        add(
                            call("weight", vec![var("head")]),
                            call("weights", vec![var("tail")]),
                        ),
                    ),
                ),
            ),
        ),
    )
}

/// A primitive's outcome charged `extra` steps and, when it produced a
/// value, that value's weight.
fn charge_result() -> Json {
    axioms(
        CLASSICAL,
        definition(
            "chargeResult",
            vec![
                parameter("result", outcome_t()),
                parameter("extra", nat_t()),
            ],
            outcome_t(),
            outcome_match(
                var("result"),
                Family::One,
                (
                    &["computed", "steps"],
                    produced(
                        var("computed"),
                        add(
                            add(var("steps"), var("extra")),
                            call("weight", vec![var("computed")]),
                        ),
                    ),
                ),
                (
                    &["steps"],
                    outcome("overflow", vec![add(var("steps"), var("extra"))]),
                ),
                stuck(),
                exhausted(),
            ),
        ),
    )
}

/// Bind names to values pairwise; a length mismatch is `none`.
fn bind_all(s: &Semantics) -> Json {
    recursive(
        "names",
        definition(
            "bindAll",
            vec![
                parameter("names", list_t(nat_t())),
                parameter("values", values_t()),
                parameter("environment", environment_t()),
            ],
            option_t(environment_t()),
            list_match(
                var("names"),
                list_match(
                    var("values"),
                    some(environment_t(), var("environment")),
                    &s.ignored(),
                    &s.ignored(),
                    none(environment_t()),
                ),
                "name",
                "names2",
                list_match(
                    var("values"),
                    none(environment_t()),
                    "value",
                    "values2",
                    call(
                        "bindAll",
                        vec![
                            var("names2"),
                            var("values2"),
                            cons(pair_of("name", "value"), var("environment")),
                        ],
                    ),
                ),
            ),
        ),
    )
}

fn pair_of(left: &str, right: &str) -> Json {
    pair(var(left), var(right))
}

/// A `nat` result is realized in `[0, 2^64)`; beyond it is `overflow`,
/// never a wrapped value.
fn nat_result() -> Json {
    definition(
        "natResult",
        vec![parameter("number", nat_t())],
        outcome_t(),
        ite(
            blt(var("number"), nat_wide(1 << 64)),
            done(value("nat", vec![var("number")])),
            outcome("overflow", vec![nat(0)]),
        ),
    )
}

/// An `int` result is realized in the 64-bit two's complement range.
fn int_result() -> Json {
    axioms(
        &["Quot.sound", "propext"],
        definition(
            "intResult",
            vec![parameter("number", int_t())],
            outcome_t(),
            option_match(
                prim(
                    "checked_convert",
                    vec![var("number")],
                    option_t(scalar_t("int64")),
                ),
                outcome("overflow", vec![nat(0)]),
                "bounded",
                done(value("int", vec![var("number")])),
            ),
        ),
    )
}

// --- TargetSemantics: the key order ----------------------------------------

/// LexLean has no `Ordering` literal and no match on `Ordering`; a
/// `compare_bytes` result is classified against the orderings
/// `compare_bytes` itself yields.
fn from_ordering() -> Json {
    let ordering = || scalar_t("ordering");
    let is = |sample: Json| prim("equal", vec![var("order"), sample], bool_t());
    axioms(
        &["propext"],
        definition(
            "fromOrdering",
            vec![parameter("order", ordering())],
            order_t(),
            ite(
                is(prim(
                    "compare_bytes",
                    vec![bytes("00"), bytes("01")],
                    ordering(),
                )),
                order("less"),
                ite(
                    is(prim(
                        "compare_bytes",
                        vec![bytes(""), bytes("")],
                        ordering(),
                    )),
                    order("same"),
                    order("more"),
                ),
            ),
        ),
    )
}

fn same_order() -> Json {
    let row = |less: bool, same: bool, more: bool| {
        order_match(var("right"), boolean(less), boolean(same), boolean(more))
    };
    definition(
        "sameOrder",
        vec![parameter("left", order_t()), parameter("right", order_t())],
        bool_t(),
        order_match(
            var("left"),
            row(true, false, false),
            row(false, true, false),
            row(false, false, true),
        ),
    )
}

/// The positions of the two inserted keys, in LexLean's own key order: the
/// left key was inserted with 0, so it leads exactly when it is less, and
/// equal keys collapse to one entry.
fn order_of(s: &Semantics) -> Json {
    definition(
        "orderOf",
        vec![parameter("positions", list_t(nat_t()))],
        order_t(),
        list_match(
            var("positions"),
            order("same"),
            "leading",
            "rest",
            list_match(
                var("rest"),
                order("same"),
                &s.ignored(),
                &s.ignored(),
                ite(beq(var("leading"), nat(0)), order("less"), order("more")),
            ),
        ),
    )
}

/// The name of the definition ordering two keys of `Value.<constructor>`.
fn key_order(constructor: &str) -> String {
    let mut characters = constructor.chars();
    let initial = characters.next().map(|c| c.to_ascii_uppercase());
    format!(
        "order{}{}",
        initial.into_iter().collect::<String>(),
        characters.as_str()
    )
}

/// Two keys ordered by inserting them into a LexLean map and reading back
/// the order of their values, so `compare` is LexLean's own key order by
/// construction rather than a second definition of it.
fn key_orders() -> Vec<Json> {
    KEYS.iter()
        .map(|&(constructor, kind, policy)| {
            let key = || scalar_t(kind);
            let map = || map_t(key(), nat_t());
            let inserted = prim(
                "map_insert",
                vec![
                    prim(
                        "map_insert",
                        vec![
                            map_literal(key(), nat_t(), Vec::new()),
                            var("leftKey"),
                            nat(0),
                        ],
                        map(),
                    ),
                    var("rightKey"),
                    nat(1),
                ],
                map(),
            );
            let declaration = definition(
                &key_order(constructor),
                vec![parameter("leftKey", key()), parameter("rightKey", key())],
                order_t(),
                call(
                    "orderOf",
                    vec![prim("map_values", vec![inserted], list_t(nat_t()))],
                ),
            );
            if policy.is_empty() {
                declaration
            } else {
                axioms(policy, declaration)
            }
        })
        .collect()
}

/// `compare` on two values: keys of one type by their key order, pairs and
/// lists lexicographically; values of different types are unordered.
fn compare_value(s: &Semantics) -> Json {
    let unordered = || none(order_t());
    let mut cases: Vec<Case> = KEYS
        .iter()
        .map(|&(constructor, _, _)| {
            on(
                constructor,
                &["leftKey"],
                s.value_match(
                    var("right"),
                    vec![on(
                        constructor,
                        &["rightKey"],
                        some(
                            order_t(),
                            call(
                                &key_order(constructor),
                                vec![var("leftKey"), var("rightKey")],
                            ),
                        ),
                    )],
                    unordered(),
                ),
            )
        })
        .collect();
    cases.push(on(
        "pair",
        &["leftFirst", "leftSecond"],
        s.value_match(
            var("right"),
            vec![on(
                "pair",
                &["rightFirst", "rightSecond"],
                option_match(
                    call("compareValue", vec![var("leftFirst"), var("rightFirst")]),
                    unordered(),
                    "firstOrder",
                    order_match(
                        var("firstOrder"),
                        some(order_t(), order("less")),
                        call("compareValue", vec![var("leftSecond"), var("rightSecond")]),
                        some(order_t(), order("more")),
                    ),
                ),
            )],
            unordered(),
        ),
    ));
    cases.push(on(
        "list",
        &["leftItems"],
        s.value_match(
            var("right"),
            vec![on(
                "list",
                &["rightItems"],
                call("compareValues", vec![var("leftItems"), var("rightItems")]),
            )],
            unordered(),
        ),
    ));
    axioms(
        CLASSICAL,
        mutual(
            "Comparison",
            recursive(
                "left",
                definition(
                    "compareValue",
                    vec![parameter("left", value_t()), parameter("right", value_t())],
                    option_t(order_t()),
                    s.value_match(var("left"), cases, unordered()),
                ),
            ),
        ),
    )
}

/// Lists lexicographically: a proper prefix is less.
fn compare_values(s: &Semantics) -> Json {
    let ordered = |constructor: &str| some(order_t(), order(constructor));
    axioms(
        CLASSICAL,
        mutual(
            "Comparison",
            recursive(
                "left",
                definition(
                    "compareValues",
                    vec![
                        parameter("left", values_t()),
                        parameter("right", values_t()),
                    ],
                    option_t(order_t()),
                    list_match(
                        var("left"),
                        list_match(
                            var("right"),
                            ordered("same"),
                            &s.ignored(),
                            &s.ignored(),
                            ordered("less"),
                        ),
                        "leftHead",
                        "leftTail",
                        list_match(
                            var("right"),
                            ordered("more"),
                            "rightHead",
                            "rightTail",
                            option_match(
                                call("compareValue", vec![var("leftHead"), var("rightHead")]),
                                none(order_t()),
                                "headOrder",
                                order_match(
                                    var("headOrder"),
                                    ordered("less"),
                                    call("compareValues", vec![var("leftTail"), var("rightTail")]),
                                    ordered("more"),
                                ),
                            ),
                        ),
                    ),
                ),
            ),
        ),
    )
}

// --- TargetSemantics: shapes -----------------------------------------------

/// The fields a shape binds when `value` has that shape, or `none`: what a
/// `match` arm sees.
fn destruct(s: &Semantics) -> Json {
    let fields = |items: Vec<Json>| some_values(values(items));
    let is_order = |constructor: &str| {
        on(
            "ordering",
            &["order"],
            ite(
                call("sameOrder", vec![var("order"), order(constructor)]),
                fields(vec![]),
                no_values(),
            ),
        )
    };
    let one = |constructor: &'static str, case: Case| {
        on(
            constructor,
            &[],
            s.value_match(var("value"), vec![case], no_values()),
        )
    };
    let mut cases = vec![
        one("none", on("none", &[], fields(vec![]))),
        one("some", on("some", &["inner"], fields(vec![var("inner")]))),
        one("ok", on("ok", &["inner"], fields(vec![var("inner")]))),
        one("error", on("error", &["inner"], fields(vec![var("inner")]))),
        one(
            "nil",
            on(
                "list",
                &["items"],
                list_match(
                    var("items"),
                    fields(vec![]),
                    &s.ignored(),
                    &s.ignored(),
                    no_values(),
                ),
            ),
        ),
        one(
            "cons",
            on(
                "list",
                &["items"],
                list_match(
                    var("items"),
                    no_values(),
                    "head",
                    "tail",
                    fields(vec![var("head"), value("list", vec![var("tail")])]),
                ),
            ),
        ),
        one(
            "zero",
            on(
                "nat",
                &["number"],
                ite(beq(var("number"), nat(0)), fields(vec![]), no_values()),
            ),
        ),
        one(
            "succ",
            on(
                "nat",
                &["number"],
                ite(
                    beq(var("number"), nat(0)),
                    no_values(),
                    fields(vec![value(
                        "nat",
                        vec![prim("subtract", vec![var("number"), nat(1)], nat_t())],
                    )]),
                ),
            ),
        ),
        one(
            "pair",
            on(
                "pair",
                &["left", "right"],
                fields(vec![var("left"), var("right")]),
            ),
        ),
        one(
            "true",
            on(
                "bool",
                &["flag"],
                ite(var("flag"), fields(vec![]), no_values()),
            ),
        ),
        one(
            "false",
            on(
                "bool",
                &["flag"],
                ite(var("flag"), no_values(), fields(vec![])),
            ),
        ),
        one("unit", on("unit", &[], fields(vec![]))),
        one("lt", is_order("less")),
        one("eq", is_order("same")),
        one("gt", is_order("more")),
    ];
    cases.push(on(
        "adt",
        &["constructor"],
        s.value_match(
            var("value"),
            vec![on(
                "adt",
                &["tag", "fields"],
                ite(
                    beq(var("tag"), var("constructor")),
                    some_values(var("fields")),
                    no_values(),
                ),
            )],
            no_values(),
        ),
    ));
    definition(
        "destruct",
        vec![
            parameter("shape", syntax_t("Shape")),
            parameter("value", value_t()),
        ],
        option_t(values_t()),
        exhaustive(var("shape"), "Shape", &shape_constructors(), cases),
    )
}

/// The value a `build` of a shape makes from its operands.
fn construct(s: &Semantics) -> Json {
    let empty = |result: Json| s.operands(|[]| done(result));
    let unary =
        |constructor: &'static str| s.operands(|[operand]| done(value(constructor, vec![operand])));
    let mut cases = vec![
        on("none", &[], empty(value("none", vec![]))),
        on("some", &[], unary("some")),
        on("ok", &[], unary("ok")),
        on("error", &[], unary("error")),
        on("nil", &[], empty(value("list", vec![nil(value_t())]))),
        on(
            "cons",
            &[],
            s.operands(|[head, tail]| {
                s.value_match(
                    tail,
                    vec![on(
                        "list",
                        &["items"],
                        done(value("list", vec![cons(head, var("items"))])),
                    )],
                    stuck(),
                )
            }),
        ),
        on("zero", &[], empty(value("nat", vec![nat(0)]))),
        on(
            "succ",
            &[],
            s.operands(|[number]| {
                s.value_match(
                    number,
                    vec![on(
                        "nat",
                        &["number"],
                        call("natResult", vec![add(var("number"), nat(1))]),
                    )],
                    stuck(),
                )
            }),
        ),
        on(
            "pair",
            &[],
            s.operands(|[left, right]| done(value("pair", vec![left, right]))),
        ),
        on("true", &[], empty(value("bool", vec![boolean(true)]))),
        on("false", &[], empty(value("bool", vec![boolean(false)]))),
        on("unit", &[], empty(value("unit", vec![]))),
        on("lt", &[], empty(value("ordering", vec![order("less")]))),
        on("eq", &[], empty(value("ordering", vec![order("same")]))),
        on("gt", &[], empty(value("ordering", vec![order("more")]))),
    ];
    cases.push(on(
        "adt",
        &["constructor"],
        done(value("adt", vec![var("constructor"), var("values")])),
    ));
    definition(
        "construct",
        vec![
            parameter("shape", syntax_t("Shape")),
            parameter("values", values_t()),
        ],
        outcome_t(),
        exhaustive(var("shape"), "Shape", &shape_constructors(), cases),
    )
}

