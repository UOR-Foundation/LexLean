//! The production realization calculus itself (SPEC.md §17.14), as the
//! `compiler` project states it to Lean: its syntax (`TargetSyntax`), its
//! denotation (`TargetSemantics`), the encoders of LexLean collection values
//! that fixture statements compare against (`TargetOracle`), the `Main`
//! entrypoint, and the project's configuration.
//!
//! The modules' semantic data is a few hundred kilobytes of canonical JSON,
//! which no reviewer reads; the calculus is read here instead, as the terms
//! that build it. The committed files are exactly what [`files`] renders,
//! which `cargo xtask check-calculus` enforces, so the JSON is never edited
//! by hand and a change to the calculus is a change to this file.

