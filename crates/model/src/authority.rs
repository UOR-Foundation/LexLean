//! The source-authority audit (R1, `NS-06`): the only hand-edited normative
//! inputs of the repository are the `.lex.tex` modules of `spec/`.
//!
//! A normative file is either a projection of those modules or a hand-written
//! document on a closed list that restates nothing the register or the
//! registry says. The projections themselves are compared byte for byte by
//! [`crate::project::Projection::check_committed`]; this finds what a byte
//! comparison cannot, which is a second source standing beside the first.

use std::collections::BTreeSet;
use std::path::Path;

use crate::{project::Projection, Model, ModelError};

/// The notice SPEC.md carries as the projection of its chapter modules.
pub const SPEC_NOTICE: &str =
    "> **Generated.** This file is the projection of the modules of `spec/src`";

/// The marker that opens each generated document the model renders.
pub const GENERATED_MARKER: &str = "<!-- @generated by `cargo xtask validate-model --write` from";

/// The hand-written documents at the repository root. None of them is
/// normative: SPEC.md is, and is generated. `AGENTS.md` assigns the rule
/// numbers (SPEC.md §27.2) and states no register row.
pub const HAND_WRITTEN: [&str; 4] = ["AGENTS.md", "CHANGELOG.md", "README.md", "VERIFICATION.md"];

/// The shortest statement whose verbatim restatement counts as a second copy
/// of the register: shorter ones are phrases any document may use.
const RESTATEMENT_MIN: usize = 40;

fn refuse(message: String) -> ModelError {
    ModelError::Inconsistent(format!("R1: {message} (NS-06)"))
}

fn skipped(name: &str) -> bool {
    matches!(
        name,
        "target" | ".git" | ".lexlean" | ".lake" | "node_modules" | "expected"
    )
}

/// Audit the repository rooted at `root`; the summary line on success.
///
/// # Errors
///
/// Fails naming the file that is a second source, or a projection that does
/// not say where it comes from.
pub fn audit(root: &Path, model: &Model, projection: &Projection) -> Result<String, ModelError> {
    let io = |path: &Path, error| ModelError::Io(path.to_path_buf(), error);

    // `model/` holds the four projected files and the vendored copies the
    // authority register names, and nothing else.
    let projected: BTreeSet<&str> = projection.files().iter().map(|(path, _)| *path).collect();
    let vendored: BTreeSet<String> = model
        .authorities
        .authority
        .iter()
        .filter_map(|authority| authority.vendored.clone())
        .collect();
    let directory = root.join("model");
    for entry in std::fs::read_dir(&directory).map_err(|e| io(&directory, e))? {
        let entry = entry.map_err(|e| io(&directory, e))?;
        let name = entry.file_name().to_string_lossy().into_owned();
        let relative = format!("model/{name}");
        if name == "authorities" && entry.path().is_dir() {
            let copies = entry.path();
            for copy in std::fs::read_dir(&copies).map_err(|e| io(&copies, e))? {
                let copy = copy.map_err(|e| io(&copies, e))?;
                let path = format!("model/authorities/{}", copy.file_name().to_string_lossy());
                if !vendored.contains(&path) {
                    return Err(refuse(format!(
                        "{path} is a hand-written file in model/ that no authority row vendors"
                    )));
                }
            }
        } else if !projected.contains(relative.as_str()) {
            return Err(refuse(format!(
                "{relative} is a file of model/ that is not a projection of spec/src"
            )));
        }
    }

    // Every Markdown file at the root is a projection or on the closed list.
    let mut documents = 0usize;
    for entry in std::fs::read_dir(root).map_err(|e| io(root, e))? {
        let entry = entry.map_err(|e| io(root, e))?;
        let name = entry.file_name().to_string_lossy().into_owned();
        if !name.ends_with(".md") {
            continue;
        }
        documents += 1;
        if !projected.contains(name.as_str())
            && name != crate::codegen::CONFORMANCE_PATH
            && name != crate::codegen::ERRORS_PATH
            && !HAND_WRITTEN.contains(&name.as_str())
        {
            return Err(refuse(format!(
                "{name} is a Markdown file at the root that is neither generated from spec/src nor on the list of hand-written documents"
            )));
        }
    }

    // A projection says where it comes from.
    let read = |relative: &str| {
        let path = root.join(relative);
        std::fs::read_to_string(&path).map_err(|e| io(&path, e))
    };
    if !read("SPEC.md")?.contains(SPEC_NOTICE) {
        return Err(refuse(
            "SPEC.md does not carry the notice that it is generated from spec/src".to_owned(),
        ));
    }
    for generated in [
        crate::codegen::CONFORMANCE_PATH,
        crate::codegen::ERRORS_PATH,
    ] {
        if !read(generated)?.starts_with(GENERATED_MARKER) {
            return Err(refuse(format!(
                "{generated} does not open with the notice that it is generated"
            )));
        }
    }

    // No hand-written document restates a registered statement: that would be
    // a second copy of the register that nothing compares.
    let statements: Vec<&str> = model
        .ids
        .id
        .iter()
        .map(|row| row.statement.as_str())
        .chain(model.errors.error.iter().map(|row| row.statement.as_str()))
        .filter(|statement| statement.len() >= RESTATEMENT_MIN)
        .collect();
    let mut scanned = 0usize;
    for entry in walkdir::WalkDir::new(root)
        .into_iter()
        .filter_entry(|e| !skipped(&e.file_name().to_string_lossy()))
    {
        let entry = entry.map_err(|e| ModelError::Inconsistent(e.to_string()))?;
        let relative = entry.path().strip_prefix(root).map_or_else(
            |_| String::new(),
            |p| p.to_string_lossy().replace('\\', "/"),
        );
        let is_markdown = relative.ends_with(".md");
        let generated = projected.contains(relative.as_str())
            || relative == crate::codegen::CONFORMANCE_PATH
            || relative == crate::codegen::ERRORS_PATH
            || relative.starts_with("model/authorities/")
            || relative.starts_with("spec/");
        if !entry.file_type().is_file() || !is_markdown || generated {
            continue;
        }
        let text = std::fs::read_to_string(entry.path()).map_err(|e| io(entry.path(), e))?;
        scanned += 1;
        if let Some(statement) = statements
            .iter()
            .find(|statement| text.contains(**statement))
        {
            return Err(refuse(format!(
                "{relative} restates a registered statement, which makes it a second source: `{}`",
                statement.chars().take(80).collect::<String>()
            )));
        }
    }
    Ok(format!(
        "{documents} root documents are projections or on the hand-written list, model/ holds only projections and vendored copies, and {scanned} hand-written Markdown files restate no registered statement"
    ))
}
