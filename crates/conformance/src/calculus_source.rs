fn from_strings() -> Json {
    recursive(
        "texts",
        definition(
            "fromStrings",
            vec![parameter("texts", list_t(string_t()))],
            values_t(),
            list_match(
                var("texts"),
                nil(value_t()),
                "text",
                "rest",
                cons(
                    value("string", vec![var("text")]),
                    call("fromStrings", vec![var("rest")]),
                ),
            ),
        ),
    )
}

/// The texts of a list of `Value.string`s; any other element is `none`.
fn to_strings(s: &Semantics) -> Json {
    let texts = || list_t(string_t());
    recursive(
        "values",
        definition(
            "toStrings",
            vec![parameter("values", values_t())],
            option_t(texts()),
            list_match(
                var("values"),
                some(texts(), nil(string_t())),
                "value",
                "rest",
                s.value_match(
                    var("value"),
                    vec![on(
                        "string",
                        &["text"],
                        option_match(
                            call("toStrings", vec![var("rest")]),
                            none(texts()),
                            "texts",
                            some(texts(), cons(var("text"), var("texts"))),
                        ),
                    )],
                    none(texts()),
                ),
            ),
        ),
    )
}

/// Every primitive by reference to the language-1.2 primitive of the same
/// meaning (§17.14), so a value of the calculus means what LexLean says it
/// means. Ill-typed operands are stuck, which a valid program never is.
#[allow(clippy::too_many_lines)]
fn primitive(s: &Semantics) -> Json {
    let nat2 = |body: fn(Json, Json) -> Json| {
        s.operands_of("nat", ["leftNumber", "rightNumber"], |[a, b]| body(a, b))
    };
    let nat3 = |body: fn(Json, Json, Json) -> Json| {
        s.operands_of(
            "nat",
            ["leftNumber", "rightNumber", "zeroNumber"],
            |[a, b, zero]| body(a, b, zero),
        )
    };
    let int2 = |body: fn(Json, Json) -> Json| {
        s.operands_of("int", ["leftNumber", "rightNumber"], |[a, b]| body(a, b))
    };
    let int3 = |body: fn(Json, Json, Json) -> Json| {
        s.operands_of(
            "int",
            ["leftNumber", "rightNumber", "zeroNumber"],
            |[a, b, zero]| body(a, b, zero),
        )
    };
    let bool2 = |connective: fn(Json, Json) -> Json| {
        s.operands_of("bool", ["leftFlag", "rightFlag"], |[a, b]| {
            done(value("bool", vec![connective(a, b)]))
        })
    };
    let bool_value = |flag: Json| done(value("bool", vec![flag]));
    let nat_result = |number: Json| call("natResult", vec![number]);
    let int_result = |number: Json| call("intResult", vec![number]);
    let nat_op = |operation: &str, operands: Vec<Json>| prim(operation, operands, nat_t());
    let int_op = |operation: &str, operands: Vec<Json>| prim(operation, operands, int_t());
    let absent = || done(value("none", vec![]));
    let present = |inner: Json| done(value("some", vec![inner]));

    // Built in this order, which fixes the numbering of their binders;
    // `exhaustive` emits them in `Prim`'s declaration order.
    let mut cases = vec![
        on(
            "natAdd",
            &[],
            nat2(|a, b| call("natResult", vec![add(a, b)])),
        ),
        on(
            "natSub",
            &[],
            nat2(|a, b| done(value("nat", vec![prim("subtract", vec![a, b], nat_t())]))),
        ),
        on(
            "natMul",
            &[],
            nat2(|a, b| call("natResult", vec![prim("multiply", vec![a, b], nat_t())])),
        ),
        on(
            "natQuot",
            &[],
            nat3(|a, b, zero| {
                done(value(
                    "nat",
                    vec![prim("quotient", vec![a, b, zero], nat_t())],
                ))
            }),
        ),
        on(
            "natRem",
            &[],
            nat3(|a, b, zero| {
                done(value(
                    "nat",
                    vec![prim("remainder", vec![a, b, zero], nat_t())],
                ))
            }),
        ),
        on(
            "natEq",
            &[],
            nat2(|a, b| done(value("bool", vec![beq(a, b)]))),
        ),
        on(
            "natLe",
            &[],
            nat2(|a, b| done(value("bool", vec![ble(a, b)]))),
        ),
        on(
            "natLt",
            &[],
            nat2(|a, b| done(value("bool", vec![blt(a, b)]))),
        ),
        // `a + b` is `a - (-b)`: LexLean's `int` has subtraction and negation
        // as primitives, and `add` is natural addition only.
        on(
            "intAdd",
            &[],
            int2(|a, b| {
                call(
                    "intResult",
                    vec![prim(
                        "subtract",
                        vec![a, prim("negate", vec![b], int_t())],
                        int_t(),
                    )],
                )
            }),
        ),
        on(
            "intSub",
            &[],
            int2(|a, b| call("intResult", vec![prim("subtract", vec![a, b], int_t())])),
        ),
        on(
            "intMul",
            &[],
            int2(|a, b| call("intResult", vec![prim("multiply", vec![a, b], int_t())])),
        ),
        on(
            "intNeg",
            &[],
            s.operands_of("int", ["leftNumber"], |[a]| {
                int_result(int_op("negate", vec![a]))
            }),
        ),
        on(
            "intQuot",
            &[],
            int3(|a, b, zero| {
                call(
                    "intResult",
                    vec![prim("quotient", vec![a, b, zero], int_t())],
                )
            }),
        ),
        on(
            "intRem",
            &[],
            int3(|a, b, zero| {
                call(
                    "intResult",
                    vec![prim("remainder", vec![a, b, zero], int_t())],
                )
            }),
        ),
        on("checkedAdd", &[], s.checked("checked_add")),
        on("checkedSub", &[], s.checked("checked_subtract")),
        on("checkedMul", &[], s.checked("checked_multiply")),
        on("checkedQuot", &[], s.checked("checked_quotient")),
        on(
            "checkedNeg",
            &[],
            s.fixed_one(&SIGNED, |number, name, kind| {
                optional(
                    prim("checked_negate", vec![number], option_t(scalar_t(kind))),
                    name,
                )
            }),
        ),
        on("bitAnd", &[], s.bitwise("bit_and")),
        on("bitOr", &[], s.bitwise("bit_or")),
        on("bitXor", &[], s.bitwise("bit_xor")),
        on(
            "bitNot",
            &[],
            s.fixed_one(&FIXED, |number, name, kind| {
                done(value(
                    name,
                    vec![prim("bit_not", vec![number], scalar_t(kind))],
                ))
            }),
        ),
        on("shiftLeft", &[], s.shift("shift_left")),
        on("shiftRight", &[], s.shift("shift_right")),
        on("equal", &[], equal(s)),
        on(
            "boolNot",
            &[],
            s.operands_of("bool", ["flag"], |[flag]| bool_value(not(flag))),
        ),
        on("boolAnd", &[], bool2(and)),
        on("boolOr", &[], bool2(or)),
        on(
            "append",
            &[],
            s.operands(|[left, right]| {
                let list_case = on(
                    "list",
                    &["leftItems"],
                    s.value_match(
                        right.clone(),
                        vec![on(
                            "list",
                            &["rightItems"],
                            done(value(
                                "list",
                                vec![prim(
                                    "append",
                                    vec![var("leftItems"), var("rightItems")],
                                    values_t(),
                                )],
                            )),
                        )],
                        stuck(),
                    ),
                );
                let bytes_case = on(
                    "bytes",
                    &["leftBytes"],
                    s.value_match(
                        right,
                        vec![on(
                            "bytes",
                            &["rightBytes"],
                            done(value(
                                "bytes",
                                vec![prim(
                                    "append",
                                    vec![var("leftBytes"), var("rightBytes")],
                                    scalar_t("bytes"),
                                )],
                            )),
                        )],
                        stuck(),
                    ),
                );
                s.value_match(left, vec![list_case, bytes_case], stuck())
            }),
        ),
        on(
            "length",
            &[],
            s.operands(|[operand]| {
                let length = |binder: &str| nat_result(nat_op("length", vec![var(binder)]));
                s.value_match(
                    operand,
                    vec![
                        on("list", &["items"], length("items")),
                        on("bytes", &["octets"], length("octets")),
                        on("string", &["text"], length("text")),
                    ],
                    stuck(),
                )
            }),
        ),
        on(
            "index",
            &[],
            s.operands(|[sequence, position]| {
                let by_sequence = s.value_match(
                    sequence,
                    vec![
                        on(
                            "list",
                            &["items"],
                            option_match(
                                prim(
                                    "index",
                                    vec![var("items"), var("position")],
                                    option_t(value_t()),
                                ),
                                absent(),
                                "item",
                                present(var("item")),
                            ),
                        ),
                        on(
                            "bytes",
                            &["octets"],
                            optional(
                                prim(
                                    "index",
                                    vec![var("octets"), var("position")],
                                    option_t(scalar_t("uint8")),
                                ),
                                "u8",
                            ),
                        ),
                    ],
                    stuck(),
                );
                s.value_match(
                    position,
                    vec![on("nat", &["position"], by_sequence)],
                    stuck(),
                )
            }),
        ),
        on(
            "slice",
            &[],
            s.operands(|[sequence, start, stop]| {
                let part = |binder: &str, ty: Json, wrap: &str| {
                    option_match(
                        prim(
                            "slice",
                            vec![var(binder), var("start"), var("stop")],
                            option_t(ty),
                        ),
                        absent(),
                        "part",
                        present(value(wrap, vec![var("part")])),
                    )
                };
                let by_sequence = s.value_match(
                    sequence,
                    vec![
                        on("list", &["items"], part("items", values_t(), "list")),
                        on(
                            "bytes",
                            &["octets"],
                            part("octets", scalar_t("bytes"), "bytes"),
                        ),
                    ],
                    stuck(),
                );
                let by_stop = s.value_match(stop, vec![on("nat", &["stop"], by_sequence)], stuck());
                s.value_match(start, vec![on("nat", &["start"], by_stop)], stuck())
            }),
        ),
        on(
            "utf8Encode",
            &[],
            s.operands_of("string", ["text"], |[text]| {
                done(value(
                    "bytes",
                    vec![prim("utf8_encode", vec![text], scalar_t("bytes"))],
                ))
            }),
        ),
        on(
            "utf8Decode",
            &[],
            s.operands_of("bytes", ["octets"], |[octets]| {
                option_match(
                    prim("utf8_decode", vec![octets], option_t(string_t())),
                    absent(),
                    "text",
                    present(value("string", vec![var("text")])),
                )
            }),
        ),
        on(
            "compareBytes",
            &[],
            s.operands_of("bytes", ["leftBytes", "rightBytes"], |[left, right]| {
                done(value(
                    "ordering",
                    vec![call(
                        "fromOrdering",
                        vec![prim(
                            "compare_bytes",
                            vec![left, right],
                            scalar_t("ordering"),
                        )],
                    )],
                ))
            }),
        ),
        on(
            "splitExact",
            &[],
            s.operands(|[text, separator, count]| {
                let split = option_match(
                    prim(
                        "split_exact",
                        vec![var("text"), var("separator"), var("count")],
                        option_t(list_t(string_t())),
                    ),
                    absent(),
                    "parts",
                    present(value("list", vec![call("fromStrings", vec![var("parts")])])),
                );
                let by_count = s.value_match(count, vec![on("u32", &["count"], split)], stuck());
                let by_separator = s.value_match(
                    separator,
                    vec![on("string", &["separator"], by_count)],
                    stuck(),
                );
                s.value_match(text, vec![on("string", &["text"], by_separator)], stuck())
            }),
        ),
        on(
            "join",
            &[],
            s.operands(|[items, separator]| {
                let joined = option_match(
                    call("toStrings", vec![var("items")]),
                    stuck(),
                    "texts",
                    done(value(
                        "string",
                        vec![prim(
                            "join",
                            vec![var("texts"), var("separator")],
                            string_t(),
                        )],
                    )),
                );
                let by_separator = s.value_match(
                    separator,
                    vec![on("string", &["separator"], joined)],
                    stuck(),
                );
                s.value_match(items, vec![on("list", &["items"], by_separator)], stuck())
            }),
        ),
        on(
            "formatDecimal",
            &[],
            s.operands(|[number]| {
                let cases = INTEGERS
                    .iter()
                    .map(|source| {
                        on(
                            source,
                            &["source"],
                            done(value(
                                "string",
                                vec![prim("format_decimal", vec![var("source")], string_t())],
                            )),
                        )
                    })
                    .collect();
                s.value_match(number, cases, stuck())
            }),
        ),
        on(
            "compare",
            &[],
            s.operands(|[left, right]| {
                option_match(
                    call("compareValue", vec![left, right]),
                    stuck(),
                    "order",
                    done(value("ordering", vec![var("order")])),
                )
            }),
        ),
    ];
    cases.push(on("convert", &["target"], convert(s)));
    cases.push(on("parseDecimal", &["target"], parse_decimal(s)));
    axioms(
        CLASSICAL,
        definition(
            "primitive",
            vec![
                parameter("operation", syntax_t("Prim")),
                parameter("values", values_t()),
            ],
            outcome_t(),
            exhaustive(var("operation"), "Prim", &prim_constructors(), cases),
        ),
    )
}

/// Scalar equality. The cases are built before the operands are named, so
/// they read the right operand through the `let` that binds it.
fn equal(s: &Semantics) -> Json {
    let right_value = || var("rightValue0");
    let mut cases: Vec<Case> = EQUATABLE
        .iter()
        .map(|constructor| {
            on(
                constructor,
                &["leftValue"],
                s.value_match(
                    right_value(),
                    vec![on(
                        constructor,
                        &["rightValue"],
                        done(value(
                            "bool",
                            vec![prim(
                                "equal",
                                vec![var("leftValue"), var("rightValue")],
                                bool_t(),
                            )],
                        )),
                    )],
                    stuck(),
                ),
            )
        })
        .collect();
    // `Order` is the calculus's own type, so its equality is `sameOrder`.
    cases.push(on(
        "ordering",
        &["leftOrder"],
        s.value_match(
            right_value(),
            vec![on(
                "ordering",
                &["rightOrder"],
                done(value(
                    "bool",
                    vec![call("sameOrder", vec![var("leftOrder"), var("rightOrder")])],
                )),
            )],
            stuck(),
        ),
    ));
    s.operands(|[left, right]| {
        let_in(
            "rightValue0",
            value_t(),
            right,
            s.value_match(left, cases, stuck()),
        )
    })
}

/// Checked conversion of any integer to the `target` width: out of range is
/// `Value.none`.
fn convert(s: &Semantics) -> Json {
    s.operands(|[operand]| {
        kind_match(var("target"), |name, kind| {
            let cases = INTEGERS
                .iter()
                .map(|source| {
                    on(
                        source,
                        &["source"],
                        optional(
                            prim(
                                "checked_convert",
                                vec![var("source")],
                                option_t(scalar_t(kind)),
                            ),
                            name,
                        ),
                    )
                })
                .collect();
            s.value_match(operand.clone(), cases, stuck())
        })
    })
}

/// Decimal parsing into an `int` or a fixed width. Unparsable text is
/// `Value.none`; an `int` outside its realization overflows, as every
/// `int` result does; any other target type is stuck.
fn parse_decimal(s: &Semantics) -> Json {
    s.operands_of("string", ["text"], |[text]| {
        let int_case = option_match(
            prim("parse_decimal", vec![text.clone()], option_t(int_t())),
            done(value("none", vec![])),
            "parsed",
            option_match(
                prim(
                    "checked_convert",
                    vec![var("parsed")],
                    option_t(scalar_t("int64")),
                ),
                outcome("overflow", vec![nat(0)]),
                "bounded",
                done(value("some", vec![value("int", vec![var("parsed")])])),
            ),
        );
        let fixed_case = kind_match(var("kind"), |name, kind| {
            optional(
                prim(
                    "parse_decimal",
                    vec![text.clone()],
                    option_t(scalar_t(kind)),
                ),
                name,
            )
        });
        s.type_match(
            var("target"),
            vec![on("int", &[], int_case), on("fixed", &["kind"], fixed_case)],
            stuck(),
        )
    })
}

// --- TargetSemantics: evaluation -------------------------------------------

/// `eval` of `expression` in `environment` with the remaining fuel.
fn eval(environment: Json, expression: Json) -> Json {
    call(
        "eval",
        vec![var("remaining"), var("program"), environment, expression],
    )
}

fn eval_list(expressions: Json) -> Json {
    call(
        "evalList",
        vec![
            var("remaining"),
            var("program"),
            var("environment"),
            expressions,
        ],
    )
}

fn one_more(steps: &str) -> Json {
    add(var(steps), nat(1))
}

/// One step per evaluated node, charged on top of the steps its operands
/// took, and every operation the evaluator performs beyond it (§17.14): the
/// bindings a local's lookup examines, each arm a match tries, a closure's
/// captures passed on application, the fields a projection skips, and a
/// primitive's operand and result weights.
#[allow(clippy::too_many_lines)]
fn expression_cases(s: &Semantics) -> Vec<Case> {
    let environment = || var("environment");
    vec![
        on(
            "value",
            &["literalType", "literal"],
            produced(var("literal"), nat(1)),
        ),
        on(
            "var",
            &["name"],
            option_match(
                call("lookup", vec![environment(), var("name")]),
                stuck(),
                "found",
                produced(
                    var("found"),
                    add(nat(1), call("depth", vec![environment(), var("name")])),
                ),
            ),
        ),
        on(
            "let",
            &["name", "boundType", "bound", "body"],
            s.propagate(
                Family::One,
                eval(environment(), var("bound")),
                ["boundValue", "boundSteps"],
                call(
                    "addSteps",
                    vec![
                        eval(
                            cons(pair_of("name", "boundValue"), environment()),
                            var("body"),
                        ),
                        one_more("boundSteps"),
                    ],
                ),
            ),
        ),
        on(
            "cond",
            &["condition", "thenBranch", "elseBranch"],
            s.propagate(
                Family::One,
                eval(environment(), var("condition")),
                ["conditionValue", "conditionSteps"],
                s.value_match(
                    var("conditionValue"),
                    vec![on(
                        "bool",
                        &["flag"],
                        call(
                            "addSteps",
                            vec![
                                ite(
                                    var("flag"),
                                    eval(environment(), var("thenBranch")),
                                    eval(environment(), var("elseBranch")),
                                ),
                                one_more("conditionSteps"),
                            ],
                        ),
                    )],
                    stuck(),
                ),
            ),
        ),
        on(
            "match",
            &["resultType", "scrutinee", "arms"],
            s.propagate(
                Family::One,
                eval(environment(), var("scrutinee")),
                ["scrutineeValue", "scrutineeSteps"],
                call(
                    "addSteps",
                    vec![
                        call(
                            "evalArms",
                            vec![
                                var("remaining"),
                                var("program"),
                                environment(),
                                var("scrutineeValue"),
                                var("arms"),
                            ],
                        ),
                        one_more("scrutineeSteps"),
                    ],
                ),
            ),
        ),
        on(
            "build",
            &["shape", "builtType", "operands"],
            s.propagate(
                Family::Many,
                eval_list(var("operands")),
                ["operandValues", "operandSteps"],
                call(
                    "addSteps",
                    vec![
                        call("construct", vec![var("shape"), var("operandValues")]),
                        one_more("operandSteps"),
                    ],
                ),
            ),
        ),
        on(
            "call",
            &["callee", "operands"],
            s.propagate(
                Family::Many,
                eval_list(var("operands")),
                ["operandValues", "operandSteps"],
                s.function_call(
                    var("callee"),
                    var("operandValues"),
                    one_more("operandSteps"),
                ),
            ),
        ),
        on(
            "closure",
            &["callee", "captures"],
            s.propagate(
                Family::Many,
                eval_list(var("captures")),
                ["captured", "captureSteps"],
                produced(
                    value("closure", vec![var("callee"), var("captured")]),
                    one_more("captureSteps"),
                ),
            ),
        ),
        // A closure's captures are passed before the operands.
        on(
            "apply",
            &["target", "operands"],
            s.propagate(
                Family::One,
                eval(environment(), var("target")),
                ["targetValue", "targetSteps"],
                s.value_match(
                    var("targetValue"),
                    vec![on(
                        "closure",
                        &["callee", "captured"],
                        s.propagate(
                            Family::Many,
                            eval_list(var("operands")),
                            ["operandValues", "operandSteps"],
                            s.function_call(
                                var("callee"),
                                prim(
                                    "append",
                                    vec![var("captured"), var("operandValues")],
                                    values_t(),
                                ),
                                add(
                                    add(add(var("targetSteps"), var("operandSteps")), nat(1)),
                                    prim("length", vec![var("captured")], nat_t()),
                                ),
                            ),
                        ),
                    )],
                    stuck(),
                ),
            ),
        ),
        on(
            "prim",
            &["operation", "operands"],
            s.propagate(
                Family::Many,
                eval_list(var("operands")),
                ["operandValues", "operandSteps"],
                call(
                    "chargeResult",
                    vec![
                        call("primitive", vec![var("operation"), var("operandValues")]),
                        add(
                            one_more("operandSteps"),
                            call("weights", vec![var("operandValues")]),
                        ),
                    ],
                ),
            ),
        ),
        on(
            "first",
            &["inner"],
            s.propagate(
                Family::One,
                eval(environment(), var("inner")),
                ["innerValue", "innerSteps"],
                s.value_match(
                    var("innerValue"),
                    vec![on(
                        "pair",
                        &["left", "right"],
                        produced(var("left"), one_more("innerSteps")),
                    )],
                    stuck(),
                ),
            ),
        ),
        on(
            "second",
            &["inner"],
            s.propagate(
                Family::One,
                eval(environment(), var("inner")),
                ["innerValue", "innerSteps"],
                s.value_match(
                    var("innerValue"),
                    vec![on(
                        "pair",
                        &["left", "right"],
                        produced(var("right"), one_more("innerSteps")),
                    )],
                    stuck(),
                ),
            ),
        ),
        on(
            "field",
            &["inner", "position"],
            s.propagate(
                Family::One,
                eval(environment(), var("inner")),
                ["innerValue", "innerSteps"],
                s.value_match(
                    var("innerValue"),
                    vec![on(
                        "adt",
                        &["tag", "fields"],
                        option_match(
                            prim(
                                "index",
                                vec![var("fields"), var("position")],
                                option_t(value_t()),
                            ),
                            stuck(),
                            "selected",
                            produced(
                                var("selected"),
                                add(one_more("innerSteps"), var("position")),
                            ),
                        ),
                    )],
                    stuck(),
                ),
            ),
        ),
    ]
}

/// The parameters every evaluation function shares, then its own.
fn evaluation_parameters(last: Json) -> Vec<Json> {
    vec![
        parameter("fuel", nat_t()),
        parameter("program", syntax_t("Program")),
        parameter("environment", environment_t()),
        last,
    ]
}

/// Structural recursion on `fuel`: running out is `exhausted`, which
/// reports only that the fuel bounded the evaluation.
fn on_fuel(exhausted: Json, remaining: Json) -> Json {
    matching(
        var("fuel"),
        vec![
            branch("Nat.zero", &[], exhausted),
            branch("Nat.succ", &["remaining"], remaining),
        ],
    )
}

fn evaluation(s: &Semantics) -> [Json; 3] {
    let expressions = expression_cases(s);
    let eval_definition = definition(
        "eval",
        evaluation_parameters(parameter("expression", syntax_t("Expr"))),
        outcome_t(),
        on_fuel(
            exhausted(),
            exhaustive(var("expression"), "Expr", &expr_constructors(), expressions),
        ),
    );
    // Operands evaluate left to right; the list's steps are the sum of its
    // elements'.
    let environment = || var("environment");
    let eval_list_definition = definition(
        "evalList",
        evaluation_parameters(parameter("expressions", list_t(syntax_t("Expr")))),
        local_t("Outcomes"),
        on_fuel(
            outcomes("exhausted", vec![]),
            list_match(
                var("expressions"),
                outcomes("values", vec![nil(value_t()), nat(0)]),
                "head",
                "rest",
                outcome_match(
                    eval(environment(), var("head")),
                    Family::One,
                    (
                        &["headValue", "headSteps"],
                        outcome_match(
                            eval_list(var("rest")),
                            Family::Many,
                            (
                                &["restValues", "restSteps"],
                                outcomes(
                                    "values",
                                    vec![
                                        cons(var("headValue"), var("restValues")),
                                        add(var("headSteps"), var("restSteps")),
                                    ],
                                ),
                            ),
                            (
                                &["restOverflow"],
                                outcomes(
                                    "overflow",
                                    vec![add(var("headSteps"), var("restOverflow"))],
                                ),
                            ),
                            outcomes("stuck", vec![]),
                            outcomes("exhausted", vec![]),
                        ),
                    ),
                    (
                        &["headOverflow"],
                        outcomes("overflow", vec![var("headOverflow")]),
                    ),
                    outcomes("stuck", vec![]),
                    outcomes("exhausted", vec![]),
                ),
            ),
        ),
    );
    // The first arm whose shape the scrutinee has is taken; none is stuck,
    // which an exhaustive match never is. Each arm tried is one step.
    let eval_arms_definition = definition(
        "evalArms",
        evaluation_parameters(parameter("scrutinee", value_t()))
            .into_iter()
            .chain([parameter("arms", list_t(syntax_t("Arm")))])
            .collect(),
        outcome_t(),
        on_fuel(
            exhausted(),
            list_match(
                var("arms"),
                stuck(),
                "first",
                "rest",
                matching(
                    var("first"),
                    vec![syntax_branch(
                        "Arm.arm",
                        &["shape", "binders", "body"],
                        option_match(
                            call("destruct", vec![var("shape"), var("scrutinee")]),
                            call(
                                "addSteps",
                                vec![
                                    call(
                                        "evalArms",
                                        vec![
                                            var("remaining"),
                                            var("program"),
                                            environment(),
                                            var("scrutinee"),
                                            var("rest"),
                                        ],
                                    ),
                                    nat(1),
                                ],
                            ),
                            "fields",
                            option_match(
                                call(
                                    "bindAll",
                                    vec![var("binders"), var("fields"), environment()],
                                ),
                                stuck(),
                                "extended",
                                call("addSteps", vec![eval(var("extended"), var("body")), nat(1)]),
                            ),
                        ),
                    )],
                ),
            ),
        ),
    );
    [eval_definition, eval_list_definition, eval_arms_definition].map(|declaration| {
        axioms(
            CLASSICAL,
            mutual("Evaluation", recursive("fuel", declaration)),
        )
    })
}

/// The denotation of a program: the entry's parameters bound to the
/// arguments, its body evaluated with `fuel`.
fn run() -> Json {
    axioms(
        CLASSICAL,
        definition(
            "run",
            vec![
                parameter("fuel", nat_t()),
                parameter("program", syntax_t("Program")),
                parameter("entry", nat_t()),
                parameter("arguments", values_t()),
            ],
            outcome_t(),
            option_match(
                prim(
                    "index",
                    vec![project(var("program"), "functions"), var("entry")],
                    option_t(function_t()),
                ),
                stuck(),
                "function",
                option_match(
                    call(
                        "bindAll",
                        vec![
                            project(var("function"), "parameters"),
                            var("arguments"),
                            nil(product_t(nat_t(), value_t())),
                        ],
                    ),
                    stuck(),
                    "environment",
                    call(
                        "eval",
                        vec![
                            var("fuel"),
                            var("program"),
                            var("environment"),
                            project(var("function"), "body"),
                        ],
                    ),
                ),
            ),
        ),
    )
}

/// The `TargetSemantics` module: outcomes and the evaluator.
#[must_use]
pub fn semantics_module() -> String {
    let s = Semantics::new();
    // Each element is built in turn, and fresh binders are numbered in that
    // order (see `Semantics`).
    let mut declarations: Vec<Json> = Vec::new();
    declarations.extend(outcome_types());
    declarations.push(add_steps());
    declarations.push(lookup());
    declarations.push(depth());
    declarations.push(bind_all(&s));
    declarations.push(nat_result());
    declarations.push(int_result());
    declarations.push(from_ordering());
    declarations.push(same_order());
    declarations.push(order_of(&s));
    declarations.extend(key_orders());
    declarations.push(compare_value(&s));
    declarations.push(compare_values(&s));
    declarations.push(weight(&s));
    declarations.push(weights());
    declarations.push(charge_result());
    declarations.push(destruct(&s));
    declarations.push(construct(&s));
    declarations.push(from_strings());
    declarations.push(to_strings(&s));
    declarations.push(primitive(&s));
    declarations.extend(evaluation(&s));
    declarations.push(run());
    module_tex(SEMANTICS, &[SYNTAX], declarations)
}

// --- TargetOracle and Main --------------------------------------------------

/// A LexLean list encoded element by element as target values, so a fixture
/// theorem can state that a library realization computes exactly what
/// LexLean's own collection primitive computes.
fn encoder(name: &str, element: Json, encode: impl Fn(Json) -> Json) -> Json {
    recursive(
        "items",
        definition(
            name,
            vec![parameter("items", list_t(element))],
            values_t(),
            list_match(
                var("items"),
                nil(value_t()),
                "item",
                "rest",
                cons(encode(var("item")), call(name, vec![var("rest")])),
            ),
        ),
    )
}

/// The `TargetOracle` module: the encoders the collection fixtures need.
#[must_use]
pub fn oracle_module() -> String {
    let declarations = vec![
        encoder("encodeNats", nat_t(), |item| value("nat", vec![item])),
        encoder("encodeInts", int_t(), |item| value("int", vec![item])),
        encoder("encodeI8s", int8_t(), |item| value("i8", vec![item])),
        encoder("encodeBools", bool_t(), |item| value("bool", vec![item])),
        encoder("encodeStrings", string_t(), |item| {
            value("string", vec![item])
        }),
        encoder("encodeNatStrings", product_t(nat_t(), string_t()), |item| {
            value(
                "pair",
                vec![
                    value("nat", vec![first(item.clone())]),
                    value("string", vec![second(item)]),
                ],
            )
        }),
        encoder(
            "encodeAdjacency",
            product_t(nat_t(), list_t(nat_t())),
            |item| {
                value(
                    "pair",
                    vec![
                        value("nat", vec![first(item.clone())]),
                        value("list", vec![call("encodeNats", vec![second(item)])]),
                    ],
                )
            },
        ),
    ];
    module_tex(ORACLE, &[SYNTAX], declarations)
}

/// The `Main` module. The project's entrypoint imports every module, so a
/// build of `compiler/` elaborates, replays, and audits all of them; its
/// one definition is the program with nothing in it.
#[must_use]
pub fn main_module() -> String {
    let empty_program = definition(
        "emptyProgram",
        Vec::new(),
        syntax_t("Program"),
        record(
            term::member(SYNTAX, "Program"),
            vec![
                ("adts", nil(syntax_t("Adt"))),
                ("functions", nil(syntax_t("Function"))),
            ],
        ),
    );
    // `Main` is the project's root, so the GNAF model and its fixtures
    // (§17.15) are elaborated, replayed, and audited only if it imports them.
    let mut imports = vec![SYNTAX, SEMANTICS, ORACLE];
    imports.extend(crate::calculus::reasoning::ORACLE_MODULES);
    imports.extend([
        FIXTURES,
        crate::calculus::reasoning::FIXTURES,
        lexlean::gnaf::MODEL,
        crate::gnaf::FIXTURES_MODULE,
    ]);
    module_tex("Main", &imports, vec![empty_program])
}

// --- project configuration -------------------------------------------------

/// `text` with `from` replaced by `to`.
///
/// # Panics
///
/// Panics when `text` does not contain `from`: the production example has
/// been changed, and the `compiler` project must not silently diverge.
fn renamed(text: &str, from: &str, to: &str) -> String {
    assert!(
        text.contains(from),
        "the production example no longer contains {from:?}"
    );
    text.replace(from, to)
}

/// The `compiler` project is configured exactly as the production example
/// (same toolchain, lexicon source, and limits) under its own name, so it
/// passes the gates of §28.6 on the same terms as that example.
fn configuration() -> [(&'static str, String); 4] {
    let lexlean = renamed(
        &renamed(
            include_str!("../../../examples/production/lexlean.toml"),
            "name = \"production\"",
            "name = \"compiler\"",
        ),
        "module_prefix = \"Production\"",
        "module_prefix = \"Compiler\"",
    );
    [
        ("compiler/lexlean.toml", lexlean),
        (
            "compiler/lakefile.toml",
            renamed(
                include_str!("../../../examples/production/lakefile.toml"),
                "production_host",
                "compiler_host",
            ),
        ),
        (
            "compiler/lake-manifest.json",
            renamed(
                include_str!("../../../examples/production/lake-manifest.json"),
                "production_host",
                "compiler_host",
            ),
        ),
        (
            "compiler/lean-toolchain",
            include_str!("../../../examples/production/lean-toolchain").to_owned(),
        ),
    ]
}

/// Every file this module generates, by path relative to the repository
/// root.
#[must_use]
pub fn files() -> BTreeMap<String, Vec<u8>> {
    let mut out: BTreeMap<String, Vec<u8>> = configuration()
        .into_iter()
        .map(|(path, text)| (path.to_owned(), text.into_bytes()))
        .collect();
    for (module, text) in [
        (SYNTAX, syntax_module()),
        (SEMANTICS, semantics_module()),
        (ORACLE, oracle_module()),
        ("Main", main_module()),
    ] {
        out.insert(format!("compiler/src/{module}.lex.tex"), text.into_bytes());
    }
    for (module, text) in crate::calculus::reasoning::oracle_modules() {
        out.insert(format!("compiler/src/{module}.lex.tex"), text.into_bytes());
    }
    out
}
