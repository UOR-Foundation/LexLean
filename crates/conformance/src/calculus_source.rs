fn environment_t() -> Json {
    list_t(product_t(nat_t(), value_t()))
}
fn outcome_t() -> Json {
    local_t("Outcome")
}
fn function_t() -> Json {
    syntax_t("Function")
}

fn outcome(constructor: &str, arguments: Vec<Json>) -> Json {
    ctor(&format!("Outcome.{constructor}"), arguments)
}
fn outcomes(constructor: &str, arguments: Vec<Json>) -> Json {
    ctor(&format!("Outcomes.{constructor}"), arguments)
}
fn stuck() -> Json {
    outcome("stuck", Vec::new())
}
fn exhausted() -> Json {
    outcome("exhausted", Vec::new())
}
/// A value outcome charged `steps`.
fn produced(result: Json, steps: Json) -> Json {
    outcome("value", vec![result, steps])
}
/// A value outcome charged nothing beyond what its caller charges: a
/// primitive's or a constructor's result, whose step `eval` counts.
fn done(result: Json) -> Json {
    produced(result, nat(0))
}
fn order(constructor: &str) -> Json {
    syntax_ctor(&format!("Order.{constructor}"), Vec::new())
}
/// A list of values, for `destruct`'s fields.
fn values(items: Vec<Json>) -> Json {
    list(value_t(), items)
}
fn some_values(items: Json) -> Json {
    some(values_t(), items)
}
fn no_values() -> Json {
    none(values_t())
}

/// Which outcome family a match inspects: one expression's, or a list's.
#[derive(Clone, Copy)]
enum Family {
    One,
    Many,
}

/// A match on an outcome. Its value case binds the value (or values) and
/// the steps taken; its overflow case binds the steps taken.
fn outcome_match(
    scrutinee: Json,
    family: Family,
    value: (&[&str], Json),
    overflow: (&[&str], Json),
    stuck: Json,
    exhausted: Json,
) -> Json {
    let (family, produced) = match family {
        Family::One => ("Outcome", "value"),
        Family::Many => ("Outcomes", "values"),
    };
    matching(
        scrutinee,
        vec![
            branch(&format!("{family}.{produced}"), value.0, value.1),
            branch(&format!("{family}.overflow"), overflow.0, overflow.1),
            branch(&format!("{family}.stuck"), &[], stuck),
            branch(&format!("{family}.exhausted"), &[], exhausted),
        ],
    )
}

fn option_match(scrutinee: Json, absent: Json, binder: &str, present: Json) -> Json {
    matching(
        scrutinee,
        vec![
            branch("Option.none", &[], absent),
            branch("Option.some", &[binder], present),
        ],
    )
}

fn list_match(scrutinee: Json, empty: Json, head: &str, tail: &str, nonempty: Json) -> Json {
    matching(
        scrutinee,
        vec![
            branch("List.nil", &[], empty),
            branch("List.cons", &[head, tail], nonempty),
        ],
    )
}

fn order_match(scrutinee: Json, less: Json, same: Json, more: Json) -> Json {
    matching(
        scrutinee,
        vec![
            syntax_branch("Order.less", &[], less),
            syntax_branch("Order.same", &[], same),
            syntax_branch("Order.more", &[], more),
        ],
    )
}

/// A match on an `IntKind`, its body built for each fixed width in turn.
fn kind_match(scrutinee: Json, mut body: impl FnMut(&str, &str) -> Json) -> Json {
    matching(
        scrutinee,
        FIXED
            .iter()
            .map(|(name, kind)| syntax_branch(&format!("IntKind.{name}"), &[], body(name, kind)))
            .collect(),
    )
}

/// `none` or `some` of a primitive's optional result, as a value outcome:
/// a checked operation that fails is `Value.none`, never stuck.
fn optional(result: Json, constructor: &str) -> Json {
    option_match(
        result,
        done(value("none", Vec::new())),
        "result",
        done(value("some", vec![value(constructor, vec![var("result")])])),
    )
}

/// One case of a match on a `TargetSyntax` type.
struct Case {
    constructor: &'static str,
    binders: Vec<String>,
    body: Json,
}

fn on(constructor: &'static str, binders: &[&str], body: Json) -> Case {
    Case {
        constructor,
        binders: owned(binders),
        body,
    }
}

fn take_case(cases: &mut Vec<Case>, constructor: &str) -> Option<Case> {
    let position = cases
        .iter()
        .position(|case| case.constructor == constructor)?;
    Some(cases.remove(position))
}

fn case_branch(ty: &str, case: Case) -> Json {
    lx::branch(
        term::member(SYNTAX, &format!("{ty}.{}", case.constructor)),
        case.binders,
        case.body,
    )
}

/// A match on a `TargetSyntax` type with a case for every constructor. The
/// branches follow the declaration, whatever order the cases were built in.
///
/// # Panics
///
/// Panics when a constructor has no case or a case names no constructor.
fn exhaustive(
    scrutinee: Json,
    ty: &str,
    constructors: &Constructors,
    mut cases: Vec<Case>,
) -> Json {
    let branches = constructors
        .iter()
        .map(|(constructor, _)| {
            let case = take_case(&mut cases, constructor)
                .unwrap_or_else(|| panic!("{ty}.{constructor} has no case"));
            case_branch(ty, case)
        })
        .collect();
    assert!(cases.is_empty(), "a {ty} case names no constructor");
    matching(scrutinee, branches)
}

// --- TargetSemantics: the builder ------------------------------------------

/// Builds `TargetSemantics` terms that need binders of their own.
///
/// A branch must bind every field of its constructor, and a binder the body
/// never reads is drawn fresh: `ignored`, `argument`, `rest`, `steps`,
/// `function`, `bound`, numbered in one sequence across the module. The
/// numbering is part of the committed bytes, so the order in which terms
/// are built is load-bearing: a term's sub-terms (its arguments, in Rust's
/// left-to-right evaluation) draw before the term itself, and reordering two
/// definitions renumbers every binder after them.
struct Semantics {
    drawn: Cell<u32>,
}

impl Semantics {
    fn new() -> Self {
        Semantics {
            drawn: Cell::new(0),
        }
    }

    fn fresh(&self, base: &str) -> String {
        self.drawn.set(self.drawn.get() + 1);
        format!("{base}{}", self.drawn.get())
    }

    fn ignored(&self) -> String {
        self.fresh("ignored")
    }

    /// A match on a `TargetSyntax` type where every constructor without a
    /// case takes `default`, its fields bound and ignored.
    fn match_or(
        &self,
        scrutinee: Json,
        ty: &str,
        constructors: &Constructors,
        mut cases: Vec<Case>,
        default: &Json,
    ) -> Json {
        let branches = constructors
            .iter()
            .map(|(constructor, fields)| {
                let case = take_case(&mut cases, constructor).unwrap_or_else(|| Case {
                    constructor,
                    binders: fields.iter().map(|_| self.ignored()).collect(),
                    body: default.clone(),
                });
                case_branch(ty, case)
            })
            .collect();
        assert!(cases.is_empty(), "a {ty} case names no constructor");
        matching(scrutinee, branches)
    }

    fn value_match(&self, scrutinee: Json, cases: Vec<Case>, default: Json) -> Json {
        self.match_or(scrutinee, "Value", &value_constructors(), cases, &default)
    }

    fn type_match(&self, scrutinee: Json, cases: Vec<Case>, default: Json) -> Json {
        self.match_or(scrutinee, "Ty", &ty_constructors(), cases, &default)
    }

    /// Destructure the operand list `values` into exactly `N` operands; any
    /// other length is stuck.
    fn operands<const N: usize>(&self, body: impl FnOnce([Json; N]) -> Json) -> Json {
        let names: Vec<String> = (0..N).map(|_| self.fresh("argument")).collect();
        let rests: Vec<String> = (0..N).map(|_| self.fresh("rest")).collect();
        let exact = body(std::array::from_fn(|index| var(&names[index])));
        let remainder = |index: usize| {
            if index == 0 {
                var("values")
            } else {
                var(&rests[index - 1])
            }
        };
        let mut term = list_match(
            remainder(N),
            exact,
            &self.ignored(),
            &self.ignored(),
            stuck(),
        );
        for index in (0..N).rev() {
            term = list_match(
                remainder(index),
                stuck(),
                &names[index],
                &rests[index],
                term,
            );
        }
        term
    }

    /// `N` operands that must all be `Value.<constructor>`, unwrapped into
    /// `binders`; anything else is stuck.
    fn operands_of<const N: usize>(
        &self,
        constructor: &'static str,
        binders: [&str; N],
        body: impl FnOnce([Json; N]) -> Json,
    ) -> Json {
        self.operands(|operands: [Json; N]| {
            let mut term = body(binders.map(var));
            for (operand, binder) in operands.into_iter().zip(binders).rev() {
                term = self.value_match(operand, vec![on(constructor, &[binder], term)], stuck());
            }
            term
        })
    }

    /// Two operands of one fixed width, unwrapped as `leftNumber` and
    /// `rightNumber`; mixed widths are stuck.
    fn fixed_pair(&self, body: impl Fn(Json, Json, &'static str, &str) -> Json) -> Json {
        self.operands(|[left, right]| {
            let cases = FIXED
                .iter()
                .map(|&(name, kind)| {
                    let inner = self.value_match(
                        right.clone(),
                        vec![on(
                            name,
                            &["rightNumber"],
                            body(var("leftNumber"), var("rightNumber"), name, kind),
                        )],
                        stuck(),
                    );
                    on(name, &["leftNumber"], inner)
                })
                .collect();
            self.value_match(left, cases, stuck())
        })
    }

    /// One operand of any of the fixed widths `widths`, unwrapped as
    /// `leftNumber`.
    fn fixed_one(
        &self,
        widths: &[(&'static str, &str)],
        body: impl Fn(Json, &'static str, &str) -> Json,
    ) -> Json {
        self.operands(|[operand]| {
            let cases = widths
                .iter()
                .map(|&(name, kind)| on(name, &["leftNumber"], body(var("leftNumber"), name, kind)))
                .collect();
            self.value_match(operand, cases, stuck())
        })
    }

    /// A checked fixed-width operation: overflow is `Value.none`.
    fn checked(&self, operation: &str) -> Json {
        self.fixed_pair(|left, right, name, kind| {
            optional(
                prim(operation, vec![left, right], option_t(scalar_t(kind))),
                name,
            )
        })
    }

    fn bitwise(&self, operation: &str) -> Json {
        self.fixed_pair(|left, right, name, kind| {
            done(value(
                name,
                vec![prim(operation, vec![left, right], scalar_t(kind))],
            ))
        })
    }

    /// A shift of any fixed width by a `u32` amount; an amount at or beyond
    /// the width is `Value.none`.
    fn shift(&self, operation: &str) -> Json {
        self.operands(|[number, amount]| {
            let by_width = FIXED
                .iter()
                .map(|&(name, kind)| {
                    on(
                        name,
                        &["leftNumber"],
                        optional(
                            prim(
                                operation,
                                vec![var("leftNumber"), var("amount")],
                                option_t(scalar_t(kind)),
                            ),
                            name,
                        ),
                    )
                })
                .collect();
            self.value_match(
                amount,
                vec![on(
                    "u32",
                    &["amount"],
                    self.value_match(number, by_width, stuck()),
                )],
                stuck(),
            )
        })
    }

    /// Continue with `scrutinee`'s value, binding it and its steps; any
    /// other outcome passes through, an overflow charged this node's step.
    fn propagate(&self, family: Family, scrutinee: Json, binders: [&str; 2], then: Json) -> Json {
        let steps = self.fresh("steps");
        outcome_match(
            scrutinee,
            family,
            (&binders, then),
            (
                &[&steps],
                outcome("overflow", vec![add(var(&steps), nat(1))]),
            ),
            stuck(),
            exhausted(),
        )
    }

    /// Call function `index` of the program on `arguments`: its body runs in
    /// a fresh environment of its parameters alone, and the call is charged
    /// `steps` on top of the body's.
    fn function_call(&self, index: Json, arguments: Json, steps: Json) -> Json {
        let function = self.fresh("function");
        let bound = self.fresh("bound");
        option_match(
            prim(
                "index",
                vec![project(var("program"), "functions"), index],
                option_t(function_t()),
            ),
            stuck(),
            &function,
            option_match(
                call(
                    "bindAll",
                    vec![
                        project(var(&function), "parameters"),
                        arguments,
                        nil(product_t(nat_t(), value_t())),
                    ],
                ),
                stuck(),
                &bound,
                call(
                    "addSteps",
                    vec![eval(var(&bound), project(var(&function), "body")), steps],
                ),
            ),
        )
    }
}

